/**
 * Lot catalogue.
 *
 * Live lots are positioned a short, whole number of hours ahead of the moment
 * this module is evaluated, so the auction room always has genuinely running
 * clocks. Sold lots sit behind the completed Heritage & Provenance sale.
 *
 * `currentBid` / `bidCount` / `bidderCount` are the SSR seed values. Once a
 * client subscribes, the live store supersedes them (EFFECT-05).
 *
 * NOTE: representative sample content for a demonstration build.
 */

import type { Lot, LotCategory } from '@/lib/types';
import { AUCTION_OFFSETS } from './auctions';

const HOUR = 3_600_000;
const DAY = 86_400_000;

const hoursFromNow = (h: number) => new Date(Date.now() + h * HOUR).toISOString();
const daysFromNow = (d: number, hour = 19, minute = 0) => {
  const t = new Date(Date.now() + d * DAY);
  return new Date(
    Date.UTC(t.getUTCFullYear(), t.getUTCMonth(), t.getUTCDate(), hour - 3, minute, 0, 0),
  ).toISOString();
};

/** Accent hues per category, sampled from the design source's own palette. */
const ACCENT: Record<LotCategory, string> = {
  paintings: '#FFE468',
  sculpture: '#8CC641',
  photography: '#272630',
  jewellery: '#FFE468',
  textiles: '#8CC641',
  ceramics: '#FFE468',
};

type LotInput = Omit<Lot, 'id' | 'accent' | 'artistLocation'> & {
  accent?: string;
  artistLocation?: string;
};

const ARTIST_LOCATIONS: Record<string, string> = {
  'wanjiru-kamau': 'Nairobi, Kenya',
  'hassan-mwinyi': 'Lamu, Kenya',
  'achieng-odhiambo': 'Kisumu, Kenya',
  'joseph-kimathi': 'Nyeri, Kenya',
  'nakato-nabirye': 'Kampala, Uganda',
  'selam-tesfaye': 'Addis Ababa, Ethiopia',
  'zawadi-mushi': 'Dar es Salaam, Tanzania',
  'amara-nkemdirim': 'Nairobi, Kenya',
  'baraka-otieno': 'Mombasa, Kenya',
};

let seq = 0;
function lot(input: LotInput): Lot {
  seq += 1;
  return {
    id: `lot-${input.lotNumber}`,
    accent: input.accent ?? ACCENT[input.category],
    artistLocation: input.artistLocation ?? ARTIST_LOCATIONS[input.artistSlug] ?? 'East Africa',
    ...input,
  };
}

