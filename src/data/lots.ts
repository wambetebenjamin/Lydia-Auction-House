/** Similar lots: same artist first, then same category, then same decade of value. */
export function similarLots(lot: Lot, limit = 6): Lot[] {
  const pool = lots.filter((l) => l.id !== lot.id);
  const score = (candidate: Lot): number => {
    let s = 0;
    if (candidate.artistSlug === lot.artistSlug) s += 100;
    if (candidate.category === lot.category) s += 40;
    const midpoint = (lot.estimateLow + lot.estimateHigh) / 2;
    const candidateMidpoint = (candidate.estimateLow + candidate.estimateHigh) / 2;
    const ratio = Math.abs(candidateMidpoint - midpoint) / Math.max(midpoint, 1);
    s += Math.max(0, 30 - ratio * 30);
    if (candidate.status === 'live') s += 12;
    return s;
  };
  return pool.sort((a, b) => score(b) - score(a)).slice(0, limit);
}

